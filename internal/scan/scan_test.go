func pattern(expr string) config.Pattern {
	return config.Pattern{Regexp: regexp.MustCompile(expr)}
}

var jobFuncs = config.FuncMatch{Exported: true, FirstParam: "ctx", Name: pattern("Job$")}

var (
	archiveJob = Item{Name: "ArchiveJob", Package: "report", Dir: "jobs/report", File: "jobs/report/report.go"}
	buildJob   = Item{Name: "BuildJob", Receiver: "Generic", Package: "report", Dir: "jobs/report", File: "jobs/report/report.go"}
	renameJob  = Item{Name: "RenameJob", Package: "renamed", Dir: "jobs/go-renamed", File: "jobs/go-renamed/renamed.go"}
	sendJob    = Item{Name: "SendJob", Receiver: "Worker", Package: "email", Dir: "jobs/email", File: "jobs/email/email.go"}
	stringer   = Item{Name: "StringerJob", Package: "report", Dir: "jobs/report", File: "jobs/report/kind_string.go"}
	fakeJob    = Item{Name: "FakeEmailJob", Package: "email_test", Dir: "jobs/email", File: "jobs/email/email_test.go"}
)

func emailItem(name, receiver string) Item {
	return Item{Name: name, Receiver: receiver, Package: "email", Dir: "jobs/email", File: "jobs/email/email.go"}
}

func TestRun(t *testing.T) {
	tests := []struct {
		name string
		scan config.Scan
		want []Item
	}{
		{
			name: "filters by export, first parameter, and name",
			scan: config.Scan{Dirs: []string{"jobs/*"}, Funcs: jobFuncs},
			want: []Item{archiveJob, buildJob, renameJob, sendJob, stringer},
		},
		{
			name: "includes test files when asked",
			scan: config.Scan{Dirs: []string{"jobs/*"}, IncludeTests: true, Funcs: jobFuncs},
			want: []Item{archiveJob, buildJob, fakeJob, renameJob, sendJob, stringer},
		},
		{
			name: "without filters matches every declaration",
			scan: config.Scan{Dirs: []string{"jobs/email"}},
			want: []Item{
				emailItem("NewSendJobInput", ""),
				emailItem("SendJob", "Worker"),
				emailItem("SendJobOptions", ""),
				emailItem("Unnamed", ""),
				emailItem("retryJob", "Worker"),
			},
		},
		{
			name: "deduplicates directories matched by several patterns",
			scan: config.Scan{Dirs: []string{"jobs/*", "jobs/report"}, Funcs: config.FuncMatch{Name: pattern("^Archive")}},
			want: []Item{archiveJob},
		},
		{
			name: "skips adder's outputs but scans other generated code",
			scan: config.Scan{Dirs: []string{"jobs/report"}, Funcs: config.FuncMatch{Name: pattern("^(Generated|Stringer)Job$")}},
			want: []Item{stringer},
		},
		{
			name: "package name comes from the package clause",
			scan: config.Scan{Dirs: []string{"jobs/go-renamed"}},
			want: []Item{renameJob},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Run(t.Context(), sources, tt.scan)
			if err != nil {
				t.Fatalf("Run() error = %v", err)
			}
			if !slices.Equal(got, tt.want) {
				t.Errorf("Run() =\n%+v\nwant\n%+v", got, tt.want)
			}
		})
	}
}

func TestRunErrors(t *testing.T) {
	tests := []struct {
		name     string
		fsys     fstest.MapFS
		dirs     []string
		canceled bool
		wantCode diag.Code
		wantPos  diag.Pos
		wantIs   error
	}{
		{name: "no match", fsys: sources, dirs: []string{"plugins/*"}, wantCode: diag.NoMatch},
		{name: "file not directory", fsys: sources, dirs: []string{"jobs/README.md"}, wantCode: diag.NoMatch},
		{name: "bad glob", fsys: sources, dirs: []string{"jobs/["}, wantCode: diag.InvalidValue},
		{
			name:     "go syntax",
			fsys:     fstest.MapFS{"broken/a.go": file("package broken\n\nfunc {")},
			dirs:     []string{"broken"},
			wantCode: diag.GoSyntax,
			wantPos:  diag.Pos{File: "broken/a.go", Line: 3, Column: 6},
		},
		{name: "canceled", fsys: sources, dirs: []string{"jobs/*"}, canceled: true, wantIs: context.Canceled},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			ctx := t.Context()
			if tt.canceled {
				var cancel context.CancelFunc
				ctx, cancel = context.WithCancel(ctx)
				cancel()
			}

			_, err := Run(ctx, tt.fsys, config.Scan{Dirs: tt.dirs})
			if tt.wantIs != nil {
				if !errors.Is(err, tt.wantIs) {
					t.Fatalf("Run() error = %v, want %v", err, tt.wantIs)
				}
				return
			}
			list := diag.From(err)
			if len(list) != 1 || list[0].Code != tt.wantCode || list[0].Pos != tt.wantPos {
				t.Fatalf("Run() error = %#v, want code %s at %v", list, tt.wantCode, tt.wantPos)
			}
		})
	}
}
