func pattern(expr string) config.Pattern {
	return config.Pattern{Regexp: regexp.MustCompile(expr)}
}

var jobFuncs = config.FuncMatch{Exported: true, FirstParam: "ctx", Name: pattern("Job$")}

// id identifies an item by its file and its qualified name.
func id(it Item) string {
	if it.Receiver != "" {
		return it.File + " " + it.Receiver + "." + it.Name
	}
	return it.File + " " + it.Name
}

func TestRun(t *testing.T) {
	tests := []struct {
		name string
		scan config.Scan
		want []string
	}{
		{
			name: "filters by export, first parameter, and name",
			scan: config.Scan{Dirs: []string{"jobs/*"}, Funcs: jobFuncs},
			want: []string{
				"jobs/report/report.go ArchiveJob",
				"jobs/report/report.go Generic.BuildJob",
				"jobs/go-renamed/renamed.go RenameJob",
				"jobs/email/email.go Worker.SendJob",
				"jobs/report/kind_string.go StringerJob",
			},
		},
		{
			name: "includes test files when asked",
			scan: config.Scan{Dirs: []string{"jobs/email"}, IncludeTests: true, Funcs: jobFuncs},
			want: []string{"jobs/email/email_test.go FakeEmailJob", "jobs/email/email.go Worker.SendJob"},
		},
		{
			name: "without filters matches every declaration",
			scan: config.Scan{Dirs: []string{"jobs/email"}},
			want: []string{
				"jobs/email/email.go NewSendJobInput",
				"jobs/email/email.go Worker.SendJob",
				"jobs/email/email.go SendJobOptions",
				"jobs/email/email.go Unnamed",
				"jobs/email/email.go Worker.retryJob",
			},
		},
		{
			name: "skips adder's outputs but scans other generated code",
			scan: config.Scan{Dirs: []string{"jobs/report"}, Funcs: config.FuncMatch{Name: pattern("^(Generated|Stringer)Job$")}},
			want: []string{"jobs/report/kind_string.go StringerJob"},
		},
		{
			name: "plain functions only",
			scan: config.Scan{Dirs: []string{"jobs/report"}, Funcs: config.FuncMatch{Kind: config.KindFunc, Name: pattern("Job$")}},
			want: []string{"jobs/report/report.go ArchiveJob", "jobs/report/kind_string.go StringerJob"},
		},
		{
			name: "methods only",
			scan: config.Scan{Dirs: []string{"jobs/*"}, Funcs: config.FuncMatch{Kind: config.KindMethod}},
			want: []string{"jobs/report/report.go Generic.BuildJob", "jobs/email/email.go Worker.SendJob", "jobs/email/email.go Worker.retryJob"},
		},
		{
			name: "methods on a receiver, value or pointer",
			scan: config.Scan{Dirs: []string{"jobs/*"}, Funcs: config.FuncMatch{Receiver: "Worker"}},
			want: []string{"jobs/email/email.go Worker.SendJob", "jobs/email/email.go Worker.retryJob"},
		},
		{
			name: "methods on a generic receiver",
			scan: config.Scan{Dirs: []string{"jobs/*"}, Funcs: config.FuncMatch{Receiver: "Generic"}},
			want: []string{"jobs/report/report.go Generic.BuildJob"},
		},
		{
			name: "first parameter type, named or not",
			scan: config.Scan{Dirs: []string{"jobs/email"}, Funcs: config.FuncMatch{FirstParamType: "context.Context"}},
			want: []string{"jobs/email/email.go Worker.SendJob", "jobs/email/email.go Unnamed", "jobs/email/email.go Worker.retryJob"},
		},
		{
			name: "first parameter type through an import alias",
			scan: config.Scan{Dirs: []string{"types"}, Funcs: config.FuncMatch{FirstParamType: "go.temporal.io/sdk/workflow.Context"}},
			want: []string{"types/types.go Alias"},
		},
		{
			name: "first parameter type from a major version import",
			scan: config.Scan{Dirs: []string{"types"}, Funcs: config.FuncMatch{FirstParamType: "*example.com/client/v2.Options"}},
			want: []string{"types/types.go Versioned"},
		},
		{
			name: "first parameter type from a gopkg.in import",
			scan: config.Scan{Dirs: []string{"types"}, Funcs: config.FuncMatch{FirstParamType: "[]gopkg.in/yaml.v3.Node"}},
			want: []string{"types/types.go Dotted"},
		},
		{
			name: "first parameter of a local type",
			scan: config.Scan{Dirs: []string{"types"}, Funcs: config.FuncMatch{FirstParamType: "*Config"}},
			want: []string{"types/types.go Local"},
		},
		{
			name: "first parameter types written as Go writes them",
			scan: config.Scan{Dirs: []string{"types"}, Funcs: config.FuncMatch{Name: pattern("^(Variadic|Map|Callback)$"), FirstParamType: "...string"}},
			want: []string{"types/types.go Variadic"},
		},
		{
			name: "first parameter map type",
			scan: config.Scan{Dirs: []string{"types"}, Funcs: config.FuncMatch{FirstParamType: "map[string]int"}},
			want: []string{"types/types.go Map"},
		},
		{
			name: "first parameter func type ignores whitespace",
			scan: config.Scan{Dirs: []string{"types"}, Funcs: config.FuncMatch{FirstParamType: "func(int)error"}},
			want: []string{"types/types.go Callback"},
		},
		{
			name: "first parameter type that nothing has",
			scan: config.Scan{Dirs: []string{"types"}, Funcs: config.FuncMatch{FirstParamType: "workflow.Context"}},
			want: nil,
		},
		{
			name: "deduplicates directories matched by several patterns",
			scan: config.Scan{Dirs: []string{"jobs/*", "jobs/report"}, Funcs: config.FuncMatch{Name: pattern("^Archive")}},
			want: []string{"jobs/report/report.go ArchiveJob"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			items, err := Run(t.Context(), sources, "", tt.scan)
			if err != nil {
				t.Fatalf("Run() error = %v", err)
			}
			var got []string
			for _, it := range items {
				got = append(got, id(it))
			}
			if !slices.Equal(got, tt.want) {
				t.Errorf("Run() =\n%q\nwant\n%q", got, tt.want)
			}
		})
	}
}

func TestRunDirs(t *testing.T) {
	tree := fstest.MapFS{}
	for _, dir := range []string{"a", "a/b", "a/b/c", "x/b", "testdata", "vendor", ".hidden", "_old"} {
		tree["tree/"+dir+"/f.go"] = file("package p\n\nfunc F() {}\n")
	}
	tests := []struct {
		name    string
		dirs    []string
		exclude []string
		want    []string
	}{
		{name: "double star matches any depth", dirs: []string{"tree/**"}, want: []string{"tree/a", "tree/a/b", "tree/a/b/c", "tree/x/b"}},
		{name: "double star in the middle", dirs: []string{"tree/**/b"}, want: []string{"tree/a/b", "tree/x/b"}},
		{name: "single star matches one level", dirs: []string{"tree/*"}, want: []string{"tree/a"}},
		{name: "wildcards skip testdata, vendor, and hidden directories", dirs: []string{"tree/*", "tree/*/b"}, want: []string{"tree/a", "tree/a/b", "tree/x/b"}},
		{name: "explicit paths are never skipped", dirs: []string{"tree/testdata", "tree/_old"}, want: []string{"tree/_old", "tree/testdata"}},
		{name: "exclude a subtree", dirs: []string{"tree/**"}, exclude: []string{"tree/a/b/**"}, want: []string{"tree/a", "tree/x/b"}},
		{name: "exclude with a wildcard", dirs: []string{"tree/**"}, exclude: []string{"tree/x/*"}, want: []string{"tree/a", "tree/a/b", "tree/a/b/c"}},
		{name: "root directory", dirs: []string{"."}, want: nil},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			items, err := Run(t.Context(), tree, "", config.Scan{Dirs: tt.dirs, Exclude: tt.exclude})
			if err != nil {
				t.Fatalf("Run() error = %v", err)
			}
			var got []string
			for _, it := range items {
				got = append(got, it.Dir)
			}
			slices.Sort(got)
			if got = slices.Compact(got); !slices.Equal(got, tt.want) {
				t.Errorf("directories = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestRunItems(t *testing.T) {
	fsys := fstest.MapFS{
		"svc/svc.go": file(`package svc

import "context"

// Service runs jobs.
type Service struct{}

// Run starts the service.
//
//adder:register name=svc
func (s *Service) Run(ctx context.Context, name string, retries int) (err error) { return nil }

func Plain(a, b int, _ string) {}
`),
	}
	run := func(importPath string) Item {
		return Item{
			Name:       "Run",
			Kind:       "method",
			Receiver:   "Service",
			Package:    "svc",
			ImportPath: importPath,
			Dir:        "svc",
			File:       "svc/svc.go",
			Line:       11,
			Doc:        "Run starts the service.",
			Signature:  "(ctx context.Context, name string, retries int) (err error)",
			Params:     []Param{{"ctx", "context.Context"}, {"name", "string"}, {"retries", "int"}},
			Results:    []Param{{"err", "error"}},
		}
	}
	plain := func(importPath string) Item {
		return Item{
			Name:       "Plain",
			Kind:       "func",
			Package:    "svc",
			ImportPath: importPath,
			Dir:        "svc",
			File:       "svc/svc.go",
			Line:       13,
			Signature:  "(a, b int, _ string)",
			Params:     []Param{{"a", "int"}, {"b", "int"}, {"_", "string"}},
		}
	}
	tests := []struct {
		name   string
		module string
		want   []Item
	}{
		{name: "with a module", module: "example.com/m", want: []Item{plain("example.com/m/svc"), run("example.com/m/svc")}},
		{name: "without a module", module: "", want: []Item{plain(""), run("")}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Run(t.Context(), fsys, tt.module, config.Scan{Dirs: []string{"svc"}})
			if err != nil {
				t.Fatalf("Run() error = %v", err)
			}
			if !reflect.DeepEqual(got, tt.want) {
				t.Errorf("Run() =\n%#v\nwant\n%#v", got, tt.want)
			}
		})
	}
}

func TestRunErrors(t *testing.T) {
	tests := []struct {
		name     string
		fsys     fstest.MapFS
		dirs     []string
		canceled bool
		wantCode diag.Code
		wantPos  diag.Pos
		wantIs   error
	}{
		{name: "no match", fsys: sources, dirs: []string{"plugins/*"}, wantCode: diag.NoMatch},
		{name: "file not directory", fsys: sources, dirs: []string{"jobs/README.md"}, wantCode: diag.NoMatch},
		{name: "double star with nothing below", fsys: sources, dirs: []string{"plugins/**"}, wantCode: diag.NoMatch},
		{
			name:     "go syntax",
			fsys:     fstest.MapFS{"broken/a.go": file("package broken\n\nfunc {")},
			dirs:     []string{"broken"},
			wantCode: diag.GoSyntax,
			wantPos:  diag.Pos{File: "broken/a.go", Line: 3, Column: 6},
		},
		{name: "canceled", fsys: sources, dirs: []string{"jobs/*"}, canceled: true, wantIs: context.Canceled},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			ctx := t.Context()
			if tt.canceled {
				var cancel context.CancelFunc
				ctx, cancel = context.WithCancel(ctx)
				cancel()
			}

			_, err := Run(ctx, tt.fsys, "", config.Scan{Dirs: tt.dirs})
			if tt.wantIs != nil {
				if !errors.Is(err, tt.wantIs) {
					t.Fatalf("Run() error = %v, want %v", err, tt.wantIs)
				}
				return
			}
			list := diag.From(err)
			if len(list) != 1 || list[0].Code != tt.wantCode || list[0].Pos != tt.wantPos {
				t.Fatalf("Run() error = %#v, want code %s at %v", list, tt.wantCode, tt.wantPos)
			}
		})
	}
}
