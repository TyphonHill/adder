package header

import (
	"go/parser"
	"go/token"
	"testing"
)

// FuzzEnsure checks that Parse finds the header Ensure adds, and that files that already have adder's header are
// left alone.
func FuzzEnsure(f *testing.F) {
	for _, seed := range []struct{ src, source string }{
		{"package p\n", "templates/x.go.tmpl"},
		{"// Package p does things.\npackage p\n", "x.tmpl"},
		{"// Code generated by stringer; DO NOT EDIT.\n\npackage p\n", "x.tmpl"},
		{Format("a.tmpl") + "\n\npackage p\n", "b.tmpl"},
		{"//go:build ignore\n\npackage p\n", "x.tmpl"},
		{"package p\n", "odd. DO NOT EDIT. name"},
	} {
		f.Add(seed.src, seed.source)
	}
	f.Fuzz(func(t *testing.T, src, source string) {
		Parse("x.go", []byte(src)) // must not panic on any input
		if commentSafe(source) {
			for _, name := range []string{"x.yaml", "x.md", "x.html", "run.sh", "x.css"} {
				out, err := Ensure(name, []byte(src), source)
				if err != nil {
					t.Fatalf("Ensure(%q) error = %v", name, err)
				}
				if string(out) == src {
					continue // src already has a generated-code comment
				}
				if got, ok := Parse(name, out); !ok || got != source {
					t.Errorf("Parse(%q, Ensure(src, %q)) = %q, %v", name, source, got, ok)
				}
			}
		}
		file, err := parser.ParseFile(token.NewFileSet(), "", src, parser.PackageClauseOnly|parser.ParseComments)
		if err != nil {
			return
		}
		out, err := Ensure("x.go", []byte(src), source)
		if err != nil {
			t.Fatalf("Ensure() error = %v for a file that parses", err)
		}
		if _, ours := Source(file); ours {
			if string(out) != src {
				t.Errorf("Ensure() changed a file that already has adder's header:\n%s", out)
			}
			return
		}
		if !commentSafe(source) {
			return
		}
		if got, ok := Parse("x.go", out); !ok || got != source {
			t.Errorf("Parse(Ensure(src, %q)) = %q, %v", source, got, ok)
		}
	})
}

// commentSafe reports whether source can appear in a line comment unchanged.
func commentSafe(s string) bool {
	for _, r := range s {
		if r == '\n' || r == '\r' || r == 0 || r == 0xFEFF || r == '�' {
			return false
		}
	}
	return true
}
