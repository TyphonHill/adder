// Package header writes and recognizes the generated-code comment adder puts on its outputs.
package header

import (
	"bytes"
	"go/ast"
	"go/parser"
	"go/token"
	"path"
	"regexp"
	"strings"

	"typhonhill.dev/adder/internal/diag"
)

// The header text is part of adder's compatibility promise: other commands find adder's outputs by parsing it.
const (
	prefix = "Code generated by adder from "
	suffix = ". DO NOT EDIT."
)

// comment is a language's syntax for a one-line comment.
type comment struct{ open, close string }

func (c comment) line(text string) string { return c.open + text + c.close }

var (
	slashes = comment{"// ", ""}
	hash    = comment{"# ", ""}
	dashes  = comment{"-- ", ""}
	block   = comment{"/* ", " */"}
	markup  = comment{"<!-- ", " -->"}
)

// languages lists, for each comment syntax, the lowercase file extensions that use it, in sorted order. Go is
// handled separately. The list is frozen within v1 (docs/compatibility.md), since adding an extension changes what
// adder writes for files of that type.
var languages = []struct {
	comment
	exts string
}{
	{slashes, ".c .cc .cjs .cpp .cs .cts .cxx .dart .h .hh .hpp .java .js .jsx .kt .kts .mjs .mts .proto .rs .scala .swift .ts .tsx"},
	{hash, ".bash .dockerfile .hcl .mk .nix .pl .pm .ps1 .psm1 .py .pyi .r .rb .sh .tf .tfvars .toml .yaml .yml .zsh"},
	{dashes, ".hs .lua .sql"},
	{block, ".css .sass .scss"},
	{markup, ".htm .html .markdown .md .svg .vue .xml"},
}

// byExt maps each extension in languages to its comment syntax.
var byExt = func() map[string]comment {
	m := make(map[string]comment)
	for _, lang := range languages {
		for ext := range strings.FieldsSeq(lang.exts) {
			m[ext] = lang.comment
		}
	}
	return m
}()

// byName maps file names without a telling extension to their comment syntax.
var byName = map[string]comment{"Dockerfile": hash, "Makefile": hash, "makefile": hash, "GNUmakefile": hash}

func syntaxFor(name string) (comment, bool) {
	base := path.Base(name)
	if c, ok := byName[base]; ok {
		return c, true
	}
	c, ok := byExt[strings.ToLower(path.Ext(base))]
	return c, ok
}

func isGo(name string) bool { return path.Ext(name) == ".go" }

// Format returns the generated-code comment adder writes in Go outputs rendered from source.
func Format(source string) string {
	return slashes.line(prefix + source + suffix)
}

// Supported reports whether outputs called name get a header, from their extension or file name.
func Supported(name string) bool {
	_, ok := syntaxFor(name)
	return ok || isGo(name)
}

// Ensure adds adder's header, naming source, to src, the content of the output called name, unless src already
// has adder's header. Another tool's generated-code comment does not count, since adder finds its own files by
// its header. Files without a known comment syntax are returned unchanged.
func Ensure(name string, src []byte, source string) ([]byte, error) {
	if isGo(name) {
		return ensureGo(src, source)
	}
	c, ok := syntaxFor(name)
	if !ok {
		return src, nil
	}
	if _, ours := Parse(name, src); ours {
		return src, nil
	}
	start := preambleEnd(name, src)
	out := make([]byte, 0, len(src)+len(prefix)+len(source)+len(suffix)+16)
	out = append(out, src[:start]...)
	if start > 0 && src[start-1] != '\n' {
		out = append(out, '\n')
	}
	out = append(out, c.line(prefix+source+suffix)+"\n"...)
	return append(out, src[start:]...), nil
}

func ensureGo(src []byte, source string) ([]byte, error) {
	file, err := parseGo(src)
	if err != nil {
		return nil, diag.Wrap(diag.InvalidOutput, diag.Pos{File: source}, err)
	}
	if _, ours := Source(file); ours {
		return src, nil
	}
	// The blank line keeps the header from becoming the package doc comment.
	return append([]byte(Format(source)+"\n\n"), src...), nil
}

// Parse returns the template named by adder's header in src, the content of the file called name, reporting
// false for files adder did not generate.
func Parse(name string, src []byte) (source string, ok bool) {
	if isGo(name) {
		file, err := parseGo(src)
		if err != nil {
			return "", false
		}
		return Source(file)
	}
	c, ok := syntaxFor(name)
	if !ok {
		return "", false
	}
	// Only where Ensure writes it: a header anywhere else may be text quoted in a file people own, and Parse
	// decides which files derive removes.
	line, _, _ := strings.Cut(string(src[preambleEnd(name, src):]), "\n")
	if rest, found := strings.CutPrefix(strings.TrimSuffix(line, "\r"), c.open+prefix); found {
		if source, found := strings.CutSuffix(rest, suffix+c.close); found {
			return source, true
		}
	}
	return "", false
}

// foreign matches the generated-code comment of any tool, following Go's convention.
var foreign = regexp.MustCompile(`^Code generated .* DO NOT EDIT\.$`)

// Foreign reports whether src, the content of the file called name, has a generated-code comment that is not
// adder's: in a Go file where Go looks for one, and otherwise in the comment lines it starts with.
func Foreign(name string, src []byte) bool {
	if _, ours := Parse(name, src); ours {
		return false
	}
	if isGo(name) {
		file, err := parseGo(src)
		return err == nil && ast.IsGenerated(file)
	}
	c, ok := syntaxFor(name)
	if !ok {
		return false
	}
	for line := range strings.Lines(string(src[preambleEnd(name, src):])) {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		text, found := strings.CutPrefix(line, strings.TrimSpace(c.open))
		if !found {
			return false
		}
		if foreign.MatchString(strings.TrimSpace(strings.TrimSuffix(text, strings.TrimSpace(c.close)))) {
			return true
		}
	}
	return false
}

// Source is Parse for a Go file that is already parsed. The file must have been parsed with parser.ParseComments.
func Source(file *ast.File) (source string, ok bool) {
	for _, group := range file.Comments {
		for _, c := range group.List {
			if c.Pos() > file.Package {
				return "", false
			}
			if rest, found := strings.CutPrefix(c.Text, "// "+prefix); found {
				if source, found := strings.CutSuffix(rest, suffix); found {
					return source, true
				}
			}
		}
	}
	return "", false
}

func parseGo(src []byte) (*ast.File, error) {
	return parser.ParseFile(token.NewFileSet(), "", src, parser.PackageClauseOnly|parser.ParseComments)
}

// preambleEnd returns where a header goes in src: after a leading #! line or XML declaration, or after Markdown
// front matter, all of which must stay first.
func preambleEnd(name string, src []byte) int {
	firstLine := func() int {
		if i := bytes.IndexByte(src, '\n'); i >= 0 {
			return i + 1
		}
		return len(src)
	}
	switch ext := strings.ToLower(path.Ext(name)); {
	case bytes.HasPrefix(src, []byte("#!")), bytes.HasPrefix(src, []byte("<?xml")):
		return firstLine()
	case (ext == ".md" || ext == ".markdown") && bytes.HasPrefix(src, []byte("---\n")):
		if i := bytes.Index(src[4:], []byte("\n---\n")); i >= 0 {
			return 4 + i + len("\n---\n")
		}
	}
	return 0
}
