// Package header writes and recognizes the generated-code comment adder puts on its Go outputs.
package header

import (
	"go/ast"
	"go/parser"
	"go/token"
	"strings"

	"github.com/TyphonHill/adder/internal/diag"
)

// The header format is part of adder's compatibility promise: other commands find adder's outputs by parsing it.
const (
	prefix = "// Code generated by adder from "
	suffix = ". DO NOT EDIT."
)

// Format returns the generated-code comment adder writes for outputs rendered from source.
func Format(source string) string {
	return prefix + source + suffix
}

// Ensure prepends Go's standard generated-code comment to src unless it already has one.
func Ensure(src []byte, source string) ([]byte, error) {
	file, err := parse(src)
	if err != nil {
		return nil, diag.Wrap(diag.InvalidOutput, diag.Pos{File: source}, err)
	}
	if ast.IsGenerated(file) {
		return src, nil
	}
	// The blank line keeps the header from becoming the package doc comment.
	return append([]byte(Format(source)+"\n\n"), src...), nil
}

// Parse returns the template named by an adder header in src, reporting false for files adder did not generate.
func Parse(src []byte) (source string, ok bool) {
	file, err := parse(src)
	if err != nil {
		return "", false
	}
	return Source(file)
}

// Source is Parse for a file that is already parsed. The file must have been parsed with parser.ParseComments.
func Source(file *ast.File) (source string, ok bool) {
	for _, group := range file.Comments {
		for _, c := range group.List {
			if c.Pos() > file.Package {
				return "", false
			}
			if rest, found := strings.CutPrefix(c.Text, prefix); found {
				if source, found := strings.CutSuffix(rest, suffix); found {
					return source, true
				}
			}
		}
	}
	return "", false
}

func parse(src []byte) (*ast.File, error) {
	return parser.ParseFile(token.NewFileSet(), "", src, parser.PackageClauseOnly|parser.ParseComments)
}
