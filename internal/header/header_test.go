func TestEnsure(t *testing.T) {
	const added = "// Code generated by adder from templates/x.go.tmpl. DO NOT EDIT.\n\n"
	tests := []struct {
		name    string
		src     string
		want    string
		wantErr bool
	}{
		{
			name: "adds header",
			src:  "package x\n",
			want: added + "package x\n",
		},
		{
			name: "keeps adder's header",
			src:  "// Code generated by adder from templates/x.go.tmpl. DO NOT EDIT.\n\npackage x\n",
			want: "// Code generated by adder from templates/x.go.tmpl. DO NOT EDIT.\n\npackage x\n",
		},
		{
			name: "keeps adder's header after a license comment",
			src:  "// Copyright 2026 Example.\n\n// Code generated by adder from t.tmpl. DO NOT EDIT.\n\npackage x\n",
			want: "// Copyright 2026 Example.\n\n// Code generated by adder from t.tmpl. DO NOT EDIT.\n\npackage x\n",
		},
		{
			name: "adds header above another tool's",
			src:  "// Code generated by mockgen. DO NOT EDIT.\n\npackage x\n",
			want: added + "// Code generated by mockgen. DO NOT EDIT.\n\npackage x\n",
		},
		{
			name: "adds header above build constraints",
			src:  "//go:build linux\n\npackage x\n",
			want: added + "//go:build linux\n\npackage x\n",
		},
		{
			name: "adds header when the existing one lacks the final period",
			src:  "// Package x does things.\n// Code generated maybe. DO NOT EDIT\npackage x\n",
			want: added + "// Package x does things.\n// Code generated maybe. DO NOT EDIT\npackage x\n",
		},
		{
			name:    "invalid go",
			src:     "not go",
			wantErr: true,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Ensure("x.go", []byte(tt.src), "templates/x.go.tmpl")
			if (err != nil) != tt.wantErr {
				t.Fatalf("Ensure() error = %v, wantErr %v", err, tt.wantErr)
			}
			if tt.wantErr {
				return
			}
			if string(got) != tt.want {
				t.Errorf("Ensure() =\n%q\nwant\n%q", got, tt.want)
			}

			file, err := parser.ParseFile(token.NewFileSet(), "", got, parser.ParseComments)
			if err != nil {
				t.Fatalf("result does not parse: %v", err)
			}
			if !ast.IsGenerated(file) {
				t.Error("result is not recognized as generated code")
			}
			if formatted, err := format.Source(got); err != nil || string(formatted) != string(got) {
				t.Errorf("result is not gofmt-clean: %v", err)
			}
		})
	}
}

func TestParse(t *testing.T) {
	ensured, err := Ensure("x.go", []byte("package x\n"), "templates/drivers.go.tmpl")
	if err != nil {
		t.Fatal(err)
	}
	tests := []struct {
		name       string
		src        string
		wantSource string
		wantOK     bool
	}{
		{name: "adder header", src: Format("templates/x.go.tmpl") + "\n\npackage x\n", wantSource: "templates/x.go.tmpl", wantOK: true},
		{name: "written by Ensure", src: string(ensured), wantSource: "templates/drivers.go.tmpl", wantOK: true},
		{name: "after a license comment", src: "// Copyright 2026 Example.\n\n" + Format("t.tmpl") + "\n\npackage x\n", wantSource: "t.tmpl", wantOK: true},
		{name: "another generator", src: "// Code generated by stringer. DO NOT EDIT.\n\npackage x\n"},
		{name: "handwritten", src: "package x\n"},
		{name: "header after package clause", src: "package x\n\n" + Format("t.tmpl") + "\n"},
		{name: "not go", src: "not go"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			source, ok := Parse("x.go", []byte(tt.src))
			if source != tt.wantSource || ok != tt.wantOK {
				t.Errorf("Parse() = %q, %v, want %q, %v", source, ok, tt.wantSource, tt.wantOK)
			}
		})
	}
}

func TestEnsureOtherLanguages(t *testing.T) {
	const source = "templates/x.tmpl"
	tests := []struct {
		name string
		file string
		src  string
		want string
	}{
		{name: "hash comment", file: "deploy/app.yaml", src: "kind: Service\n", want: "# Code generated by adder from templates/x.tmpl. DO NOT EDIT.\nkind: Service\n"},
		{name: "extension case is ignored", file: "x.YML", src: "a: 1\n", want: "# Code generated by adder from templates/x.tmpl. DO NOT EDIT.\na: 1\n"},
		{name: "slash comment", file: "web/api.ts", src: "export {};\n", want: "// Code generated by adder from templates/x.tmpl. DO NOT EDIT.\nexport {};\n"},
		{name: "dash comment", file: "db/schema.sql", src: "SELECT 1;\n", want: "-- Code generated by adder from templates/x.tmpl. DO NOT EDIT.\nSELECT 1;\n"},
		{name: "block comment", file: "site.css", src: "a {}\n", want: "/* Code generated by adder from templates/x.tmpl. DO NOT EDIT. */\na {}\n"},
		{name: "markup comment", file: "docs/list.md", src: "# Drivers\n", want: "<!-- Code generated by adder from templates/x.tmpl. DO NOT EDIT. -->\n# Drivers\n"},
		{name: "file name", file: "build/Makefile", src: "all:\n", want: "# Code generated by adder from templates/x.tmpl. DO NOT EDIT.\nall:\n"},
		{name: "after a shebang", file: "run.sh", src: "#!/bin/sh\necho hi\n", want: "#!/bin/sh\n# Code generated by adder from templates/x.tmpl. DO NOT EDIT.\necho hi\n"},
		{name: "after an XML declaration", file: "a.svg", src: "<?xml version=\"1.0\"?>\n<svg/>\n", want: "<?xml version=\"1.0\"?>\n<!-- Code generated by adder from templates/x.tmpl. DO NOT EDIT. -->\n<svg/>\n"},
		{name: "after front matter", file: "a.md", src: "---\ntitle: A\n---\nText\n", want: "---\ntitle: A\n---\n<!-- Code generated by adder from templates/x.tmpl. DO NOT EDIT. -->\nText\n"},
		{name: "unterminated front matter", file: "a.md", src: "---\ntitle: A\n", want: "<!-- Code generated by adder from templates/x.tmpl. DO NOT EDIT. -->\n---\ntitle: A\n"},
		{name: "a shebang without a newline", file: "run.sh", src: "#!/bin/sh", want: "#!/bin/sh\n# Code generated by adder from templates/x.tmpl. DO NOT EDIT.\n"},
		{name: "keeps adder's header", file: "a.py", src: "# Code generated by adder from t.tmpl. DO NOT EDIT.\nx = 1\n", want: "# Code generated by adder from t.tmpl. DO NOT EDIT.\nx = 1\n"},
		{name: "keeps adder's header after a shebang", file: "a.sh", src: "#!/bin/sh\n# Code generated by adder from t.tmpl. DO NOT EDIT.\n", want: "#!/bin/sh\n# Code generated by adder from t.tmpl. DO NOT EDIT.\n"},
		{name: "adds header above another tool's", file: "a.py", src: "# Code generated by protoc. DO NOT EDIT.\nx = 1\n", want: "# Code generated by adder from templates/x.tmpl. DO NOT EDIT.\n# Code generated by protoc. DO NOT EDIT.\nx = 1\n"},
		{name: "adds header when adder's is not where adder writes it", file: "a.yaml", src: "a: 1\n# Code generated by adder from t.tmpl. DO NOT EDIT.\n", want: "# Code generated by adder from templates/x.tmpl. DO NOT EDIT.\na: 1\n# Code generated by adder from t.tmpl. DO NOT EDIT.\n"},
		{name: "no comment syntax", file: "data.json", src: "{}\n", want: "{}\n"},
		{name: "no extension", file: "LICENSE", src: "text\n", want: "text\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Ensure(tt.file, []byte(tt.src), source)
			if err != nil {
				t.Fatal(err)
			}
			if string(got) != tt.want {
				t.Errorf("Ensure(%q) =\n%q\nwant\n%q", tt.file, got, tt.want)
			}
			if wantOK := Supported(tt.file) && tt.want != tt.src; wantOK {
				if got, ok := Parse(tt.file, got); !ok || got != source {
					t.Errorf("Parse(Ensure()) = %q, %v, want %q", got, ok, source)
				}
			}
		})
	}
}

