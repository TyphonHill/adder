package header

import (
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"testing"
)

func TestEnsure(t *testing.T) {
	const added = "// Code generated by adder from templates/x.go.tmpl. DO NOT EDIT.\n\n"
	tests := []struct {
		name    string
		src     string
		want    string
		wantErr bool
	}{
		{
			name: "adds header",
			src:  "package x\n",
			want: added + "package x\n",
		},
		{
			name: "keeps existing header",
			src:  "// Code generated by other. DO NOT EDIT.\n\npackage x\n",
			want: "// Code generated by other. DO NOT EDIT.\n\npackage x\n",
		},
		{
			name: "keeps header after a license comment",
			src:  "// Copyright 2026 Example.\n\n// Code generated by other. DO NOT EDIT.\n\npackage x\n",
			want: "// Copyright 2026 Example.\n\n// Code generated by other. DO NOT EDIT.\n\npackage x\n",
		},
		{
			name: "adds header above build constraints",
			src:  "//go:build linux\n\npackage x\n",
			want: added + "//go:build linux\n\npackage x\n",
		},
		{
			name: "adds header when the existing one lacks the final period",
			src:  "// Package x does things.\n// Code generated maybe. DO NOT EDIT\npackage x\n",
			want: added + "// Package x does things.\n// Code generated maybe. DO NOT EDIT\npackage x\n",
		},
		{
			name:    "invalid go",
			src:     "not go",
			wantErr: true,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Ensure([]byte(tt.src), "templates/x.go.tmpl")
			if (err != nil) != tt.wantErr {
				t.Fatalf("Ensure() error = %v, wantErr %v", err, tt.wantErr)
			}
			if tt.wantErr {
				return
			}
			if string(got) != tt.want {
				t.Errorf("Ensure() =\n%q\nwant\n%q", got, tt.want)
			}

			file, err := parser.ParseFile(token.NewFileSet(), "", got, parser.ParseComments)
			if err != nil {
				t.Fatalf("result does not parse: %v", err)
			}
			if !ast.IsGenerated(file) {
				t.Error("result is not recognized as generated code")
			}
			if formatted, err := format.Source(got); err != nil || string(formatted) != string(got) {
				t.Errorf("result is not gofmt-clean: %v", err)
			}
		})
	}
}

func TestParse(t *testing.T) {
	ensured, err := Ensure([]byte("package x\n"), "templates/drivers.go.tmpl")
	if err != nil {
		t.Fatal(err)
	}
	tests := []struct {
		name       string
		src        string
		wantSource string
		wantOK     bool
	}{
		{name: "adder header", src: Format("templates/x.go.tmpl") + "\n\npackage x\n", wantSource: "templates/x.go.tmpl", wantOK: true},
		{name: "written by Ensure", src: string(ensured), wantSource: "templates/drivers.go.tmpl", wantOK: true},
		{name: "after a license comment", src: "// Copyright 2026 Example.\n\n" + Format("t.tmpl") + "\n\npackage x\n", wantSource: "t.tmpl", wantOK: true},
		{name: "another generator", src: "// Code generated by stringer. DO NOT EDIT.\n\npackage x\n"},
		{name: "handwritten", src: "package x\n"},
		{name: "header after package clause", src: "package x\n\n" + Format("t.tmpl") + "\n"},
		{name: "not go", src: "not go"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			source, ok := Parse([]byte(tt.src))
			if source != tt.wantSource || ok != tt.wantOK {
				t.Errorf("Parse() = %q, %v, want %q, %v", source, ok, tt.wantSource, tt.wantOK)
			}
		})
	}
}
