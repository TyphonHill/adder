// testPacks holds pack file systems by name.
type testPacks map[string]fstest.MapFS

func (p testPacks) FS(name string) (fs.FS, bool) {
	fsys, ok := p[name]
	return fsys, ok
}

func (testPacks) Funcs() template.FuncMap { return nil }

// storePack lists the functions of the directories each use names, with a registry and one file per function.
var storePack = fstest.MapFS{
	"pack.yaml": {Data: []byte(`version: 1
options:
  dirs: {type: list}
  out: {}
partials: [templates/_*.tmpl]
derive:
  scans:
    Ctors: {dirs: {option: dirs}, funcs: {name: ^New}}
  outputs:
    - {template: templates/registry.go.tmpl, path: "{{ .Options.out }}/registry.gen.go"}
    - {template: templates/each.go.tmpl, each: Ctors, path: "{{ .Options.out }}/{{ .Item.Name | toSnakeCase }}.gen.go"}
`)},
	"templates/_pkg.tmpl":        {Data: []byte(`{{ define "pkg" }}package {{ trimPrefix "gen/" .Options.out }}{{ end }}`)},
	"templates/registry.go.tmpl": {Data: []byte("{{ template \"pkg\" . }}\n\n// {{ range .Ctors }}{{ .Package }}.{{ .Name }} {{ end }}in {{ .Module }}\n")},
	"templates/each.go.tmpl":     {Data: []byte("{{ template \"pkg\" . }}\n\n// {{ .Item.Name }}\n")},
}

func TestPlanPacks(t *testing.T) {
	repo := fstest.MapFS{
		"go.mod":        {Data: []byte("module example.com/m\n")},
		"stores/a/a.go": {Data: []byte("package a\n\nfunc NewStore() {}\n")},
		"caches/c/c.go": {Data: []byte("package c\n\nfunc NewCache() {}\n")},
	}
	const config2 = `version: 1
packs:
  stores: {pack: store, with: {dirs: ["stores/*"], out: gen/stores}}
  caches: {pack: store, with: {dirs: ["caches/*"], out: gen/caches}}
`
	generated := func(source, body string) *fstest.MapFile {
		return &fstest.MapFile{Data: []byte(header.Format(source) + "\n\n" + body)}
	}
	tests := []struct {
		name        string
		pack        fstest.MapFS
		existing    fstest.MapFS
		wantChanges []string
		wantContent map[string]string
		wantErrs    []string
	}{
		{
			name: "each use renders with its own scans and options",
			pack: storePack,
			wantChanges: []string{
				"created gen/caches/registry.gen.go", "created gen/caches/new_cache.gen.go",
				"created gen/stores/registry.gen.go", "created gen/stores/new_store.gen.go",
			},
			wantContent: map[string]string{
				"gen/stores/registry.gen.go":  "// Code generated by adder from templates/registry.go.tmpl in pack store for stores. DO NOT EDIT.\n\npackage stores\n\n// a.NewStore in example.com/m\n",
				"gen/caches/new_cache.gen.go": "// Code generated by adder from templates/each.go.tmpl in pack store for caches. DO NOT EDIT.\n\npackage caches\n\n// NewCache\n",
			},
		},
		{
			name: "stale files belong to the use that generated them",
			pack: storePack,
			existing: fstest.MapFS{
				"gen/stores/old.gen.go":     generated("templates/each.go.tmpl in pack store for stores", "package stores\n"),
				"gen/caches/kept.gen.go":    generated("templates/each.go.tmpl in pack store for elsewhere", "package caches\n"),
				"gen/stores/handwritten.go": {Data: []byte("package stores\n")},
			},
			wantChanges: []string{
				"created gen/caches/registry.gen.go", "created gen/caches/new_cache.gen.go",
				"created gen/stores/registry.gen.go", "created gen/stores/new_store.gen.go", "removed gen/stores/old.gen.go",
			},
		},
		{
			name: "problems in a pack's templates are in the pack",
			pack: fstest.MapFS{
				"pack.yaml":                  storePack["pack.yaml"],
				"templates/_pkg.tmpl":        storePack["templates/_pkg.tmpl"],
				"templates/registry.go.tmpl": {Data: []byte("{{ template \"pkg\" . }}\n{{ .Missing }}\n")},
				"templates/each.go.tmpl":     storePack["templates/each.go.tmpl"],
			},
			wantErrs: []string{"pack store: templates/registry.go.tmpl:2:3 template-exec", "pack store: templates/registry.go.tmpl:2:3 template-exec"},
		},
		{
			name:     "a partial that matches nothing",
			pack:     fstest.MapFS{"pack.yaml": storePack["pack.yaml"], "templates/registry.go.tmpl": {}, "templates/each.go.tmpl": {}},
			wantErrs: []string{"pack store: pack.yaml:5:12 no-match", "pack store: pack.yaml:5:12 no-match"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			cfg, err := config.Parse("adder.yaml", []byte(config2), testPacks{"store": tt.pack})
			if err != nil {
				t.Fatalf("Parse() error = %v", err)
			}
			existing := tt.existing
			if existing == nil {
				existing = fstest.MapFS{}
			}
			p, err := Plan(t.Context(), cfg, Sources{Repo: repo, Templates: fstest.MapFS{}, Existing: existing})
			var errs []string
			for _, d := range diag.From(err) {
				errs = append(errs, d.Pos.String()+" "+string(d.Code))
			}
			if !slices.Equal(errs, tt.wantErrs) {
				t.Fatalf("Plan() problems = %q, want %q\n%v", errs, tt.wantErrs, err)
			}
			if err != nil {
				return
			}
			var changes []string
			for _, c := range p.Changes {
				changes = append(changes, c.Status.String()+" "+c.Path)
			}
			if !slices.Equal(changes, tt.wantChanges) {
				t.Errorf("changes = %q, want %q", changes, tt.wantChanges)
			}
			for path, want := range tt.wantContent {
				i := slices.IndexFunc(p.Changes, func(c plan.Change) bool { return c.Path == path })
				if i < 0 || string(p.Changes[i].New) != want {
					t.Errorf("%s =\n%s\nwant\n%s", path, contentOf(p, i), want)
				}
			}
		})
	}
}

func contentOf(p *plan.Plan, i int) string {
	if i < 0 {
		return "(not planned)"
	}
	return strings.TrimSpace(string(p.Changes[i].New))
}

func TestExplainPack(t *testing.T) {
	cfg, err := config.Parse("adder.yaml", []byte("version: 1\npacks:\n  stores: {pack: store, with: {dirs: [\"stores/*\"], out: gen/stores}}\n"), testPacks{"store": storePack})
	if err != nil {
		t.Fatal(err)
	}
	repo := fstest.MapFS{"go.mod": {Data: []byte("module example.com/m\n")}, "stores/a/a.go": {Data: []byte("package a\n\nfunc NewStore() {}\n")}}
	p, err := Plan(t.Context(), cfg, Sources{Repo: repo, Templates: fstest.MapFS{}})
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range p.Changes {
		repo[c.Path] = &fstest.MapFile{Data: c.New}
	}
	src := Sources{Repo: repo, Templates: fstest.MapFS{}, Existing: repo}
	tests := []struct {
		name     string
		file     string
		template string
		scans    []string
	}{
		{name: "an output", file: "gen/stores/registry.gen.go", template: "templates/registry.go.tmpl in pack store for stores", scans: []string{"Ctors"}},
		{name: "an output with each", file: "gen/stores/new_store.gen.go", template: "templates/each.go.tmpl in pack store for stores", scans: []string{}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			e, err := Explain(t.Context(), cfg, src, tt.file)
			if err != nil {
				t.Fatal(err)
			}
			if e.Template != tt.template || e.Output == nil || e.Output.Use != "stores" || e.Output.Pack != "store" || !slices.Equal(e.Scans, tt.scans) || *e.Status != plan.Unchanged {
				t.Errorf("Explain() = %+v, output %+v", e, e.Output)
			}
		})
	}
}

func TestPlanPackTemplates(t *testing.T) {
	pack := fstest.MapFS{
		"pack.yaml":    {Data: []byte("version: 1\noptions: {out: {}}\npartials: [_*.tmpl]\n")},
		"_lic.tmpl":    {Data: []byte(`{{ define "lic" }}// License: {{ .Vars.License }}{{ end }}`)},
		"list.go.tmpl": {Data: []byte("{{ template \"lic\" . }}\n\npackage x\n\n// {{ range .Ctors }}{{ .Name }} {{ end }}\n")},
		"bad.go.tmpl":  {Data: []byte("package x\n\n// {{ .Options.out }}\n")},
	}
	repo := fstest.MapFS{"stores/a/a.go": {Data: []byte("package a\n\nfunc NewStore() {}\n")}}
	adderYAML := func(template string) string {
		return "version: 1\nvars: {License: MIT}\nderive:\n  scans:\n    Ctors: {dirs: [\"stores/*\"], funcs: {name: ^New}}\n  outputs:\n    - {template: " + template + ", pack: store, path: x/list.gen.go}\n"
	}
	tests := []struct {
		name     string
		template string
		want     string
		wantErrs []string
	}{
		{
			name:     "with the configuration's own data and the pack's partials",
			template: "list.go.tmpl",
			want:     "// Code generated by adder from list.go.tmpl in pack store. DO NOT EDIT.\n\n// License: MIT\n\npackage x\n\n// NewStore\n",
		},
		{name: "a problem in the pack's template", template: "bad.go.tmpl", wantErrs: []string{"pack store: bad.go.tmpl:3:14 template-exec"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			cfg, err := config.Parse("adder.yaml", []byte(adderYAML(tt.template)), testPacks{"store": pack})
			if err != nil {
				t.Fatal(err)
			}
			src := Sources{Repo: repo, Templates: fstest.MapFS{}}
			p, err := Plan(t.Context(), cfg, src)
			var errs []string
			for _, d := range diag.From(err) {
				errs = append(errs, d.Pos.String()+" "+string(d.Code))
			}
			if !slices.Equal(errs, tt.wantErrs) {
				t.Fatalf("Plan() problems = %q, want %q\n%v", errs, tt.wantErrs, err)
			}
			if err != nil {
				return
			}
			if len(p.Changes) != 1 || string(p.Changes[0].New) != tt.want {
				t.Fatalf("changes = %+v, want x/list.gen.go:\n%s", p.Changes, tt.want)
			}
			withOutput := fstest.MapFS{"x/list.gen.go": {Data: p.Changes[0].New}}
			maps.Copy(withOutput, repo)
			e, err := Explain(t.Context(), cfg, Sources{Repo: withOutput, Templates: fstest.MapFS{}, Existing: withOutput}, "x/list.gen.go")
			if err != nil || e.Output == nil || e.Output.Pack != "store" || e.Output.Use != "" || !slices.Equal(e.Scans, []string{"Ctors"}) {
				t.Errorf("Explain() = %+v, %v", e, err)
			}
		})
	}
}
